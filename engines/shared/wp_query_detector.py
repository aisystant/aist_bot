"""
Детектор запросов «про мои РП» + парсер реестра рабочих продуктов.

WP-411 Ф7. Чистые функции (без сети/БД) → полностью покрываются unit-тестами.

Зачем:
    Свободный вопрос «какие мои РП?» уходил в Claude без реестра в контексте →
    модель сочиняла правдоподобные названия (галлюцинация). Реестр
    (docs/WP-REGISTRY.md) помечен `index-health: skip` и НЕ попадает в
    семантический индекс — personal_search его не находит. Поэтому бот тянет
    реестр детерминированно по пути (вариант В), но сначала надо понять, что
    вопрос именно про личный реестр РП, а не про устройство системы РП вообще.

Две функции:
    is_wp_query(question)        — классификатор вопроса (личный реестр vs тема)
    parse_active_registry(md)    — из markdown-реестра → компактный список активных
"""

import re

# Сильные паттерны: личное местоимение прямо в ключевой фразе про РП.
# Всегда считаем личным запросом — перевешивают тематические негации.
_STRONG_PATTERNS = (
    "мои рп",
    "мой реестр",
    "мои рабочие продукты",
    "мои рабочие пакеты",
    "мои задачи",
    "мой план работ",
    "wp-registry",
    "реестр рп",
    "реестр моих",
)

# Слова-маркеры «списка/перечня». Личным делают только в паре с личным сигналом.
_LIST_STEMS = (
    "активн",
    "текущ",
    "список",
    "списка",
    "открыт",
    "сколько",
    "какие",
    "перечисл",
    "всех",
    "все мои",
)

# Личный сигнал — указывает, что речь о данных самого пользователя.
_PERSONAL_SIGNALS = (
    "мои",
    "мой",
    "моя",
    "моих",
    "у меня",
    "мне ",
    "меня",
)

# Тематические негации: вопрос об устройстве системы/метода РП, не о личных данных.
# ВАЖНО: только тематические фразы. Форматные глаголы «расскажи»/«объясни» сюда
# НЕ входят (peer-сессия 2026-06-14-07: «расскажи мои активные РП» — законный
# личный запрос). Слово «платформа» тоже исключено — слишком широкое, давало
# ложное отрицание для «мои РП на платформе».
_NEGATIONS = (
    "что такое wp",
    "что такое рп",
    "что значит рп",
    "что значит wp",
    "как работает wp",
    "как работают рп",
    "как устроен",
    "как устроена",
    "объясни систему",
    "архитектура системы",
    "зачем нужны рп",
    "зачем нужен рп",
)

# «рп»/«wp» как отдельное слово (а не подстрока в «корпус», «перпендикуляр»).
_RP_WORD = re.compile(r"\bрп\b|\bwp\b|wp-\d|рабоч\w*\s+(продукт|пакет)", re.IGNORECASE)


def _has_rp_word(q: str) -> bool:
    return bool(_RP_WORD.search(q))


def is_wp_query(question: str, strict: bool = False) -> bool:
    """True, если вопрос — про личный реестр РП пользователя.

    Порядок проверок (важен):
    1. Сильный паттерн («мои рп», «мой реестр»…) → личный запрос всегда.
    2. Тематическая негация («что такое рп», «как устроена»…) → НЕ личный.
    3. Слабый паттерн (слово-РП + маркер списка) → личный ТОЛЬКО при личном сигнале.

    strict=True — Strong-only: после проверки сильных паттернов сразу False,
    слабые не рассматриваются. Нужно на пути Гермеса (T4-full, WP-411 Ф7): там
    ложный перехват прерывает co-thinking-сессию, поэтому перехватываем только
    однозначные формулировки («мои рп», «мой реестр»), а не «какие активные».
    """
    if not question:
        return False
    q = question.lower().strip()

    if any(p in q for p in _STRONG_PATTERNS):
        return True

    if strict:
        return False

    if any(n in q for n in _NEGATIONS):
        return False

    if (
        _has_rp_word(q)
        and any(stem in q for stem in _LIST_STEMS)
        and any(sig in q for sig in _PERSONAL_SIGNALS)
    ):
        return True

    return False


def parse_active_registry(markdown: str, max_rows: int = 80) -> str:
    """Из markdown-реестра WP-REGISTRY.md → компактный список активных РП.

    Активная строка: статус 🔄 (in_progress) или ⏳ (pending), номер — чистая
    цифра (строки done/cancelled обёрнуты в ~~…~~, отбрасываются).

    Колонки реестра: `| # | P | Название | статус | путь | бюджет/комментарий |`.
    Берём только # + P + Название + статус — без бюджета/ссылок/истории
    (они повышают риск конфабуляции и едят токены).

    Returns:
        Строка вида «Активных РП: N\\nРП419 (P3, ⏳): …» или "" если активных нет.
    """
    active = []
    for line in markdown.splitlines():
        if not line.lstrip().startswith("|"):
            continue
        cells = [c.strip() for c in line.split("|")]
        # cells[0] = '' (до первого |); cells[1]=#, [2]=P, [3]=Название, [4]=статус
        if len(cells) < 5:
            continue
        num = cells[1]
        if not num.isdigit():  # шапка, разделитель |---|, ~~416~~ (done) → пропуск
            continue
        status = cells[4]
        if "🔄" not in status and "⏳" not in status:
            continue
        name_cell = cells[3]
        if "~~" in name_cell:  # подстраховка: зачёркнутое название
            continue
        name = name_cell.replace("**", "").replace("~~", "").strip()
        proj = cells[2].replace("~~", "").strip()
        active.append(f"РП{num} ({proj}, {status}): {name}")

    if not active:
        return ""

    header = f"Активных рабочих продуктов: {len(active)}\n"
    return header + "\n".join(active[:max_rows])
